/**
 * What a door container is: an nginx in front of one Traefik entrypoint, bound to
 * ONE host address.
 *
 * Pure, so the exact config and the exact container spec are tested — the old
 * forwarder shipped two bugs that only a running host revealed (nginx listening on
 * 127.0.0.1 INSIDE the container, and a config written to a path nothing mounted).
 * Both are pinned by tests here:
 *
 *   - nginx listens on every address INSIDE the container; the host-side scope
 *     comes from `PortBindings[].HostIp`, which is the only place it can come from;
 *   - the config travels in the container's environment and is written by the
 *     command itself, so there is no volume or archive upload to get wrong.
 */

import { createHash } from "node:crypto";
import { doorContainerName, type DoorLane, type NodeDoorsSetting } from "@deployer/mesh-network";

/** The local lane binds loopback only: reachable from this machine and nowhere else. */
export const LOOPBACK_DOOR_ADDRESS = "127.0.0.1";

/** Label marking a container as a door this agent owns. */
export const DOOR_LABEL = "deployer.mesh.door";
/** Label carrying the hash of everything the door was built from. */
export const DOOR_HASH_LABEL = "deployer.mesh.door.hash";

export type DoorPlan = {
	lane: DoorLane;
	name: string;
	image: string;
	network: string;
	bindAddress: string;
	port: number;
	nginxConfig: string;
	hash: string;
}

/**
 * Render the nginx config for a lane's door.
 *
 * Upstreams are resolved per request (`resolver` + variables), so nginx starts even
 * while Traefik is not resolvable yet — a static upstream would make the door fail
 * to boot exactly when it is needed as a rescue lane.
 */
export function renderDoorNginxConfig(lane: DoorLane, setting: NodeDoorsSetting): string {
	const upstreamPort =
		lane === "local" ? setting.lanes.local.upstreamPort : lane === "private" ? setting.lanes.private?.upstreamPort : setting.lanes.lan?.upstreamPort;
	if (upstreamPort === undefined) throw new Error(`lane ${lane} is disabled; no door config`);
	const rescue = lane === "local" ? setting.rescue : [];

	const lines = [
		"# Generated by deployer-mesh-agent. Do not edit: the agent rewrites it.",
		"resolver 127.0.0.11 valid=10s ipv6=off;",
		"map $http_upgrade $deployer_connection_upgrade { default upgrade; '' close; }",
		"map $host $deployer_rescue_upstream {",
		'    default "";',
		...rescue.map((route) => `    ${route.host} ${route.target}:${String(route.port)};`),
		"}",
		"server {",
		`    listen ${String(setting.entryPort)} default_server;`,
		"    client_max_body_size 0;",
		"    proxy_http_version 1.1;",
		"    proxy_buffering off;",
		"    proxy_read_timeout 1h;",
		"    proxy_set_header Host $host;",
		"    proxy_set_header Upgrade $http_upgrade;",
		"    proxy_set_header Connection $deployer_connection_upgrade;",
		"    proxy_set_header X-Real-IP $remote_addr;",
		"    location / {",
		`        set $deployer_upstream ${setting.upstream}:${String(upstreamPort)};`,
		"        proxy_pass http://$deployer_upstream;",
		// Only nginx's OWN failures (Traefik unreachable) reach the rescue lane;
		// a 502 Traefik returns from an app passes through untouched.
		"        error_page 502 503 504 = @deployer_rescue;",
		"    }",
		"    location @deployer_rescue {",
		'        if ($deployer_rescue_upstream = "") { return 502; }',
		"        proxy_pass http://$deployer_rescue_upstream;",
		"    }",
		"}",
		"",
	];
	return lines.join("\n");
}

/**
 * The doors this node should run, given the setting, its mesh address and its LAN
 * address.
 *
 * The private door needs the mesh address to bind, and the LAN door an actual
 * interface address: without one (no cluster yet, an observe-only dataplane, or a
 * host whose only interface is loopback) each is planned as absent, never as
 * 0.0.0.0 — that fallback would turn "reachable by peers" into "reachable by
 * everyone", which is exactly the mistake the address-scoped bind exists to avoid.
 */
export function planDoors(
	setting: NodeDoorsSetting,
	meshAddress: string | null,
	lanAddress: string | null,
): { desired: DoorPlan[]; absent: DoorLane[] } {
	const desired: DoorPlan[] = [];
	const absent: DoorLane[] = [];
	const plan = (lane: DoorLane, bindAddress: string): DoorPlan => {
		const nginxConfig = renderDoorNginxConfig(lane, setting);
		const name = doorContainerName(setting.namePrefix, lane);
		const hash = createHash("sha256")
			.update([setting.image, setting.network, bindAddress, String(setting.entryPort), nginxConfig].join("\n"))
			.digest("hex")
			.slice(0, 16);
		return { lane, name, image: setting.image, network: setting.network, bindAddress, port: setting.entryPort, nginxConfig, hash };
	};

	desired.push(plan("local", LOOPBACK_DOOR_ADDRESS));
	if (setting.lanes.private !== null && meshAddress !== null) desired.push(plan("private", meshAddress));
	else absent.push("private");
	if (setting.lanes.lan !== null && lanAddress !== null) desired.push(plan("lan", lanAddress));
	else absent.push("lan");
	return { desired, absent };
}

/** The Docker Engine `POST /containers/create` body for a door. */
export function doorContainerSpec(plan: DoorPlan): Record<string, unknown> {
	const portKey = `${String(plan.port)}/tcp`;
	return {
		Image: plan.image,
		Env: [`DEPLOYER_DOOR_CONF=${plan.nginxConfig}`],
		Entrypoint: ["/bin/sh", "-c"],
		Cmd: ['printf \'%s\' "$DEPLOYER_DOOR_CONF" > /etc/nginx/conf.d/default.conf && exec nginx -g "daemon off;"'],
		Labels: { [DOOR_LABEL]: plan.lane, [DOOR_HASH_LABEL]: plan.hash },
		ExposedPorts: { [portKey]: {} },
		HostConfig: {
			PortBindings: { [portKey]: [{ HostIp: plan.bindAddress, HostPort: String(plan.port) }] },
			RestartPolicy: { Name: "unless-stopped" },
			NetworkMode: plan.network,
		},
	};
}
