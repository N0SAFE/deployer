import { writeFile } from "node:fs/promises";

import { Context, Data, Effect } from "effect";

import {
	MESH_INTERFACE_MTU,
	MESH_INTERFACE_NAME,
	parseWireguardDump,
	type WireguardDump,
} from "./wireguard";

/** A host command that exited non-zero, or a config write that failed. */
export class WireguardCommandError extends Data.TaggedError("WireguardCommandError")<{
	readonly command: string;
	readonly stderr: string;
}> {}

export type CommandResult = { readonly code: number; readonly stdout: string; readonly stderr: string };

/**
 * The agent's only way into the kernel (`ip`, `wg`): a port, so every test runs without spawning a process.
 *
 * `Bun.spawn` and not a shell: arguments are never interpreted, so nothing can be injected. Both pipes are drained
 * concurrently with the exit code — reading them sequentially deadlocks once a chatty `ip` or `wg` fills one.
 */
export class HostCommands extends Context.Service<
	HostCommands,
	{
		readonly run: (command: string, args: readonly string[]) => Effect.Effect<CommandResult>;
		/** `stdin` is written and closed before the process is read: `wg pubkey` reads the private key from there. */
		readonly runWithInput: (command: string, args: readonly string[], input: string) => Effect.Effect<CommandResult>;
	}
>()("node-agent/HostCommands") {
	static readonly live = class HostCommandsImpl {
		run = (command: string, args: readonly string[]) => spawn(command, args)
		runWithInput = (command: string, args: readonly string[], input: string) => spawn(command, args, input)
	};
}

function spawn(command: string, args: readonly string[], input?: string) {
	return Effect.promise(async (): Promise<CommandResult> => {
		try {
			const proc = Bun.spawn([command, ...args], { stdin: input === undefined ? "ignore" : "pipe", stdout: "pipe", stderr: "pipe" });
			if (input !== undefined && proc.stdin !== undefined) {
				await proc.stdin.write(input);
				await proc.stdin.end();
			}
			const [stdout, stderr, code] = await Promise.all([
				new Response(proc.stdout).text(),
				new Response(proc.stderr).text(),
				proc.exited,
			]);
			return { code, stdout, stderr };
		} catch (error: unknown) {
			// A missing binary throws rather than reporting an exit code; 127 is the shell's convention.
			return { code: 127, stdout: "", stderr: error instanceof Error ? error.message : String(error) };
		}
	});
}

/** Where the interface and its `syncconf` file live. Defaults to the agent's state dir; dev can override it. */
export class WireguardPaths extends Context.Service<
	WireguardPaths,
	{ readonly interfaceName: string; readonly configPath: string }
>()("node-agent/WireguardPaths") {
	static readonly live = class WireguardPathsImpl {
		interfaceName = MESH_INTERFACE_NAME
		configPath = `${process.env.NODE_AGENT_STATE_DIR ?? "/var/lib/deployer/node-agent"}/wireguard.conf`
	};
}

export type WireguardDriverShape = {
	/** Create the interface if needed and make `address/prefix` its only address. */
	readonly ensureInterface: (
		address: string,
		prefix: number,
	) => Effect.Effect<void, WireguardCommandError, HostCommands | WireguardPaths>;
	/** Apply a rendered config with `wg syncconf` (changes only what differs). */
	readonly syncConfig: (config: string) => Effect.Effect<void, WireguardCommandError, HostCommands | WireguardPaths>;
	/** Current `wg show dump`, or null when the interface does not exist. */
	readonly dump: () => Effect.Effect<WireguardDump | null, never, HostCommands | WireguardPaths>;
	/** A fresh key pair, generated by `wg` and kept in the node's store by the caller. */
	readonly generateKeypair: () => Effect.Effect<WireguardKeypair, WireguardCommandError, HostCommands>;
	readonly removeInterface: () => Effect.Effect<void, never, HostCommands | WireguardPaths>;
};

export type WireguardKeypair = { readonly privateKey: string; readonly publicKey: string };

const must = (command: string, args: readonly string[]) =>
	Effect.gen(function* () {
		const commands = yield* HostCommands;
		const result = yield* commands.run(command, args);
		if (result.code !== 0) {
			return yield* Effect.fail(
				new WireguardCommandError({ command: `${command} ${args.join(" ")}`, stderr: result.stderr }),
			);
		}
		return result.stdout;
	});

/**
 * The kernel side of the mesh: one HOST WireGuard interface, configured with `ip` and `wg`.
 *
 * A host interface is the point: Swarm can then advertise the mesh address, and Docker can bind the private door to it.
 * A sidecar namespace made the address invisible to both.
 */
export class WireguardDriver extends Context.Service<WireguardDriver, WireguardDriverShape>()(
	"node-agent/WireguardDriver",
) {
	static readonly kernel: WireguardDriverShape = {
		ensureInterface: (address, prefix) =>
			Effect.gen(function* () {
				const paths = yield* WireguardPaths;
				const commands = yield* HostCommands;
				const name = paths.interfaceName;

				const exists = yield* commands.run("ip", ["link", "show", "dev", name]);
				if (exists.code !== 0) yield* must("ip", ["link", "add", "dev", name, "type", "wireguard"]);

				const wanted = `${address}/${String(prefix)}`;
				const shown = yield* must("ip", ["-o", "-4", "address", "show", "dev", name]);
				const current = [...shown.matchAll(/inet (\S+)/g)].map((match) => match[1]);
				if (current.length !== 1 || current[0] !== wanted) {
					// A re-derived address (collision) must REPLACE the old one, not sit beside it.
					yield* must("ip", ["address", "flush", "dev", name]);
					yield* must("ip", ["address", "add", wanted, "dev", name]);
				}

				yield* must("ip", ["link", "set", "dev", name, "mtu", String(MESH_INTERFACE_MTU), "up"]);
			}),

		syncConfig: (config) =>
			Effect.gen(function* () {
				const paths = yield* WireguardPaths;
				yield* Effect.tryPromise({
					try: () => writeFile(paths.configPath, config, { mode: 0o600 }),
					catch: () =>
						new WireguardCommandError({ command: `write ${paths.configPath}`, stderr: "config write failed" }),
				});
				yield* must("wg", ["syncconf", paths.interfaceName, paths.configPath]);
			}),

		dump: () =>
			Effect.gen(function* () {
				const paths = yield* WireguardPaths;
				const commands = yield* HostCommands;
				const result = yield* commands.run("wg", ["show", paths.interfaceName, "dump"]);
				return result.code === 0 ? parseWireguardDump(result.stdout) : null;
			}),

		generateKeypair: () =>
			Effect.gen(function* () {
				const commands = yield* HostCommands;
				const generated = yield* commands.run("wg", ["genkey"]);
				if (generated.code !== 0) {
					return yield* Effect.fail(new WireguardCommandError({ command: "wg genkey", stderr: generated.stderr }));
				}
				const privateKey = generated.stdout.trim();
				const derived = yield* commands.runWithInput("wg", ["pubkey"], `${privateKey}\n`);
				if (derived.code !== 0) {
					return yield* Effect.fail(new WireguardCommandError({ command: "wg pubkey", stderr: derived.stderr }));
				}
				return { privateKey, publicKey: derived.stdout.trim() };
			}),

		removeInterface: () =>
			Effect.gen(function* () {
				const paths = yield* WireguardPaths;
				const commands = yield* HostCommands;
				yield* commands.run("ip", ["link", "delete", "dev", paths.interfaceName]);
			}),
	};

	/**
	 * Plans and reports, never touches the kernel.
	 *
	 * For a dev machine without `NET_ADMIN`: roster, gossip and door convergence still run, and status says plainly that
	 * no interface exists.
	 */
	static readonly observeOnly: WireguardDriverShape = {
		ensureInterface: () => Effect.void,
		syncConfig: () => Effect.void,
		dump: () => Effect.succeed(null),
		generateKeypair: () =>
			Effect.fail(new WireguardCommandError({ command: "wg genkey", stderr: "the observe-only driver holds no keys" })),
		removeInterface: () => Effect.void,
	};
}
