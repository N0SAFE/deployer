#!/usr/bin/env bun
/**
 * Generate the authorization matrix page (`SEC-066`).
 *
 * The page is DERIVED, never written by hand: `authz/definition.ts` is the single declaration, and a hand-written matrix
 * is the fifth copy of the role list that drifts the first time a permission moves.
 *
 *   bun run scripts/gen-authz-matrix.ts
 *
 * Writes `apps/doc/content/docs/architecture/authz-matrix.mdx`. Re-run it in the same change set as any catalog edit; a
 * reviewer can then read the diff as "these roles gained/lost these permissions".
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import {
	BUNDLES,
	PERMISSIONS,
	SYSTEM_ROLES_TABLE,
} from "../packages/auth/src/authz/definition";

const ROOT = join(import.meta.dir, "..");
const OUT = join(ROOT, "apps/doc/content/docs/architecture/authz-matrix.mdx");

/** Roles, strongest first within each scope. */
const roles = Object.values(SYSTEM_ROLES_TABLE).sort(
	(a, b) => a.scope.localeCompare(b.scope) || b.rank - a.rank,
);

/** Permissions grouped by resource, so the matrix reads as "what this resource allows". */
const byResource = new Map<string, string[]>();
for (const permission of Object.keys(PERMISSIONS)) {
	const resource = permission.slice(0, permission.indexOf(":"));
	const list = byResource.get(resource) ?? [];
	list.push(permission);
	byResource.set(resource, list);
}

const resources = [...byResource.keys()].sort();

/** The platform and project roles are separate tables: a role only grants inside its own scope. */
const scopeRoles = (scope: "platform" | "project") => roles.filter((role) => role.scope === scope);

const riskOf = (permission: string): string => {
	const definitions: Record<string, { readonly risk: string }> = PERMISSIONS;
	return definitions[permission]?.risk ?? "?";
};

const row = (permission: string, holders: readonly { name: string; permissions: readonly string[] }[]) =>
	`| \`${permission}\` | \`${riskOf(permission)}\` | ${holders
		.map((role) => (role.permissions.includes(permission) ? "✓" : ""))
		.join(" | ")} |`;

const table = (scope: "platform" | "project") => {
	const members = scopeRoles(scope);
	const header = `| Permission | Risk | ${members.map((role) => role.label).join(" | ")} |`;
	const divider = `|---|---|${members.map(() => "---").join("|")}|`;
	const body = resources
		.filter((resource) => byResource.get(resource)?.some((p) => p.startsWith(`${resource}:`)))
		.flatMap((resource) => [
			`| **${resource}** | | ${members.map(() => "").join(" | ")} |`,
			...(byResource.get(resource) ?? [])
				.filter((permission) => members.some((role) => role.permissions.includes(permission)))
				.map((permission) => row(permission, members)),
		]);
	return [header, divider, ...body].join("\n");
};

const bundles: Record<string, Record<string, readonly string[]>> = BUNDLES;

const bundleList = Object.entries(bundles)
	.map(([name, permissions]) => {
		const granted = Object.entries(permissions)
			.flatMap(([resource, actions]) => actions.map((action) => `\`${resource}:${action}\``))
			.sort();
		return `### \`${name}\`\n\n${granted.length === 0 ? "_no permissions_" : granted.join(", ")}`;
	})
	.join("\n\n");

const content = `---
title: Authorization matrix
description: Every role and the permissions it grants, generated from the authz declaration.
---

{/* GENERATED by \`scripts/gen-authz-matrix.ts\` — do not edit. Re-run it with any catalog change. */}

## Roles

| Role | Name | Scope | Rank | Permissions |
|---|---|---|---|---|
${roles
	.map(
		(role) =>
			`| ${role.label ?? role.name} | \`${role.name}\` | ${role.scope} | ${String(role.rank)} | ${String(role.permissions.length)} |`,
	)
	.join("\n")}

A role only grants inside its SCOPE: a platform role hands out nothing at project level, and a project role grants
nothing on the platform. Rank answers "may this actor act on that account", never "what may they do".

## Platform roles

${table("platform")}

## Project roles

${table("project")}

## Bundles

A role is declared as bundles, and a bundle is a named set of permissions. Editing a bundle moves every role that
includes it.

${bundleList}
`;

writeFileSync(OUT, content);
console.log(`wrote ${OUT} (${String(roles.length)} roles, ${String(Object.keys(PERMISSIONS).length)} permissions)`);
